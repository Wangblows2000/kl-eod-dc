#!/usr/bin/env python3
"""Turn a test script (port/dc/tests/*.txt) into C data for hal_test.c. No script -> empty table."""
import sys

KEYS = {"A": 0x001, "B": 0x002, "SELECT": 0x004, "START": 0x008, "RIGHT": 0x010, "LEFT": 0x020,
        "UP": 0x040, "DOWN": 0x080, "R": 0x100, "L": 0x200}
OPS = {"press": 1, "dump": 2, "end": 3}


def main():
    out, src = sys.argv[1], sys.argv[2] if len(sys.argv) > 2 and sys.argv[2] else None
    rows = []
    if src:
        for n, line in enumerate(open(src), 1):
            line = line.split("#", 1)[0].split()
            if not line:
                continue
            op = OPS[line[0]]
            frame = int(line[1])
            length, keys = 0, 0
            if op == 1:
                length = int(line[2])
                for k in line[3:]:
                    keys |= KEYS[k]
            rows.append((frame, length, keys, op))
    with open(out, "w") as f:
        f.write("/* generated by tools/script2c.py from %s */\n#include <stdint.h>\n" % (src or "(no script)"))
        f.write("struct test_cmd { uint32_t frame, len; uint16_t keys; uint8_t op; };\n")
        f.write("const struct test_cmd hal_test_script[] = {\n")
        for r in rows or [(0, 0, 0, 0)]:
            f.write("    {%d, %d, 0x%03X, %d},\n" % r)
        f.write("};\nconst uint32_t hal_test_script_len = %d;\n" % len(rows))


if __name__ == "__main__":
    main()
