#!/usr/bin/env python3
"""Find GBA function pointers hidden in ROM data that kleod does not express symbolically.

kleod's data files mostly reference functions by name (those relocate correctly when the data is
assembled for SH-4), but some jump tables are still raw .incbin bytes. On the Dreamcast those
words would point into ARM/Thumb code in the mapped ROM image. This script finds every word in
the data region that equals a Thumb function address (|1), drops the ones that are relocations
in kleod's own objects, keeps runs of 4+ consecutive pointers (tables; isolated matches are
coincidences in compressed data), and with --emit-c writes the boot-time fixups that replace
each entry with the Dreamcast address of the same function -- both in the mapped ROM image and
in the copy assembled into the executable.
"""
import argparse
import bisect
import re
import struct
import subprocess


def elf_symbols(root):
    out = subprocess.run(["arm-none-eabi-nm", f"{root}/kleod.elf"], capture_output=True, text=True, check=True).stdout
    funcs, data = {}, []
    for line in out.splitlines():
        p = line.split()
        if len(p) != 3 or p[2].startswith("$"):
            continue
        addr = int(p[0], 16)
        if p[1] in "Tt" and 0x08000000 <= addr < 0x08051BD4 and not p[2].startswith("_"):
            funcs.setdefault(addr | 1, p[2])
        elif 0x08051BD4 <= addr < 0x08400000 and not p[2].startswith("_"):
            data.append((addr, p[2]))
    data.sort()
    return funcs, data


def symbolic_relocs(root):
    mp = open(f"{root}/kleod.map").read()
    sites = set()
    for m in re.finditer(r"^ (\.(?:rodata|data))\s+0x(0*8[0-9a-f]{6})\s+0x[0-9a-f]+\s+(\S+\.o)$", mp, re.M):
        sec, base, obj = m.group(1), int(m.group(2), 16), m.group(3)
        r = subprocess.run(["arm-none-eabi-objdump", "-r", "-j", sec, f"{root}/build/kleod/{obj}"],
                           capture_output=True, text=True).stdout
        for mm in re.finditer(r"^([0-9a-f]{8}) R_ARM_ABS32", r, re.M):
            sites.add(base + int(mm.group(1), 16))
    return sites


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--root", required=True)
    ap.add_argument("--emit-c")
    a = ap.parse_args()
    rom = open(f"{a.root}/baserom.gba", "rb").read()
    funcs, data = elf_symbols(a.root)
    relocs = symbolic_relocs(a.root)

    raw = []
    for off in range(0x51BD4, len(rom) - 3, 4):
        w = struct.unpack_from("<I", rom, off)[0]
        if w in funcs and 0x08000000 + off not in relocs:
            raw.append(0x08000000 + off)
    rawset = set(raw)
    tables = [x for x in raw if sum(1 for k in range(-3, 4) if x + 4 * k in rawset) >= 4]
    strays = [x for x in raw if x not in tables]
    print(f"symbolic code pointers in data: {len(relocs)}")
    print(f"raw code pointers in incbin data: {len(raw)} ({len(tables)} in tables, {len(strays)} isolated/coincidental)")

    if a.emit_c:
        addrs = [d[0] for d in data]
        with open(a.emit_c, "w") as f:
            f.write("/* generated by tools/scan_code_pointers.py */\n#include <stdint.h>\n\n")
            names = set()
            entries = []
            for slot in tables:
                fn = funcs[struct.unpack_from("<I", rom, slot - 0x08000000)[0]]
                i = bisect.bisect_right(addrs, slot) - 1
                sym_addr, sym = data[i]
                entries.append((slot, sym, slot - sym_addr, fn))
                names.add(fn)
            for n in sorted(names):
                f.write(f"extern void {n}(void);\n")
            for s in sorted({e[1] for e in entries}):
                f.write(f"extern char {s}[];\n")
            f.write("\nstatic const struct { uint32_t gba; char *dc; void (*fn)(void); } fixups[] = {\n")
            for slot, sym, off, fn in entries:
                f.write(f"    {{0x{slot:08X}, {sym} + 0x{off:X}, {fn}}},\n")
            f.write("};\n\nvoid hal_apply_code_ptr_fixups(void) {\n    unsigned i;\n")
            f.write("    for (i = 0; i < sizeof fixups / sizeof fixups[0]; i++) {\n")
            f.write("        *(volatile uint32_t *)fixups[i].gba = (uint32_t)fixups[i].fn;\n")
            f.write("        *(uint32_t *)fixups[i].dc = (uint32_t)fixups[i].fn;\n    }\n}\n")


if __name__ == "__main__":
    main()
