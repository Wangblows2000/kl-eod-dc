#!/usr/bin/env python3
"""Resolve every symbol the Dreamcast objects leave undefined.

* Data symbols (RAM globals placed by kleod's linker.ld, ROM data) become absolute symbols at
  their GBA address, which hal_mem maps onto Dreamcast RAM.
* Functions that only exist as GBA assembly in kleod (asm/*.s) and that no HAL file provides
  get a logging stub, so the executable links and every call is visible on the serial log.

Writes a linker script fragment and a C file of stubs, plus a human-readable report.
"""
import argparse
import subprocess
from collections import defaultdict

CODE_END = 0x08051BD4  # end of game code in the ROM (kleod: src/data/data_08051BD4.c starts here)


def nm(tool, path):
    out = subprocess.run([tool, path], capture_output=True, text=True, check=True).stdout
    for line in out.splitlines():
        parts = line.split()
        if len(parts) == 2:
            yield None, parts[0], parts[1]
        elif len(parts) == 3:
            yield int(parts[0], 16), parts[1], parts[2]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--elf", required=True, help="kleod.elf from the GBA build")
    ap.add_argument("--nm", required=True, help="sh-elf-nm")
    ap.add_argument("--out", required=True, help="linker script fragment to write")
    ap.add_argument("--stubs", required=True, help="C file of stubs to write")
    ap.add_argument("--report", required=True)
    ap.add_argument("objs", nargs="+")
    a = ap.parse_args()

    gba = {}
    for addr, typ, name in nm("arm-none-eabi-nm", a.elf):
        if addr is not None and not name.startswith("$"):
            gba.setdefault(name, (addr, typ))

    defined, undefined = set(), defaultdict(set)
    for o in a.objs:
        for addr, typ, name in nm(a.nm, o):
            n = name[1:] if name.startswith("_") else name
            if typ == "U":
                undefined[n].add(o.rsplit("/", 1)[-1])
            elif typ not in "wv":
                defined.add(n)

    # C library / libgcc routines: on the GBA they came from agbcc's libc and live in the code
    # range of kleod.elf, but on the Dreamcast newlib and libgcc provide them.
    libc = {"memcpy", "memset", "memmove", "memcmp", "strlen", "strcmp", "strcpy", "strncpy", "abs"}
    need = {n: users for n, users in undefined.items() if n not in defined and n not in libc and not n.startswith("__")}
    absolute, stubs, missing = {}, [], []
    for n in sorted(need):
        if n in gba:
            addr, typ = gba[n]
            is_code = typ in "Tt" and 0x08000000 <= addr < CODE_END
            if is_code:
                stubs.append(n)
            else:
                absolute[n] = addr
        else:
            missing.append(n)

    # libgcc/newlib/KOS provide these; the compiler driver links them.

    with open(a.out, "w") as f:
        f.write("/* generated by tools/gen_symbols.py: GBA-address symbols for the Dreamcast link */\n")
        for n, addr in sorted(absolute.items(), key=lambda kv: kv[1]):
            f.write(f"_{n} = 0x{addr:08X};\n")

    with open(a.stubs, "w") as f:
        f.write("/* generated by tools/gen_symbols.py: GBA assembly routines with no DC implementation yet */\n")
        f.write('#include "hal.h"\n\nvoid hal_stub_hit(const char *name, int *seen);\n\n')
        for n in stubs:
            f.write(f'unsigned int {n}(void) {{ static int seen; hal_stub_hit("{n}", &seen); return 0; }}\n')
        f.write('\nvoid hal_stub_hit(const char *name, int *seen) {\n    if (!*seen) { *seen = 1; hal_log("stub: %s (GBA asm, not yet ported)\\n", name); }\n}\n')

    regions = defaultdict(int)
    for n, addr in absolute.items():
        regions[{2: "EWRAM", 3: "IWRAM", 8: "ROM data"}.get(addr >> 24, hex(addr >> 24))] += 1
    with open(a.report, "w") as f:
        f.write(f"undefined after compiling game + HAL: {len(need)}\n")
        f.write(f"  resolved to fixed GBA addresses: {len(absolute)} ({dict(regions)})\n")
        f.write(f"  GBA asm routines stubbed: {len(stubs)}\n    " + " ".join(stubs) + "\n")
        f.write(f"  not in kleod.elf (KallistiOS / HAL-internal): {len(missing)}\n    " + " ".join(missing) + "\n")
    print(open(a.report).read())


if __name__ == "__main__":
    main()
